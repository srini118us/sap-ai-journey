"""
Generate synthetic vendor payment data for the payment delay labs.

Writes seed SQL (schema plus INSERT statements plus verification
queries) rather than shipping 2000 INSERT lines in the repo. Seeded,
so the output is reproducible.

The delay label is generated from a weighted formula over real
features, so the data carries learnable signal rather than noise. Two
details are deliberate:

  - COMPANY_CODE carries ZERO weight. One-hot encoded columns with no
    signal let feature importance show which inputs actually matter.
  - VENDOR_RISK_SCORE carries the LARGEST weight (2.60). Useful when
    checking whether a model finds the true strongest driver.

CATEGORY_CODE is an integer, not text. Training scripts that one-hot
encode only COMPANY_CODE will crash on any other string column.

Run
---
    python generate_payments.py > seed_payments.sql

Then load it:
    hdbsql -n <sql-endpoint>:443 -e -u <user> -p <password>
    \\i seed_payments.sql

For large scripts a Python loop is more reliable than \\i; see the
README.
"""
import random
from datetime import date, timedelta
from decimal import Decimal

random.seed(42)

N = 2000
COMPANY_CODES = ["1000", "1710", "2000", "1010"]
CATEGORIES = ["IT_SERVICES", "LOGISTICS", "RAW_MATERIAL",
              "FACILITIES", "CONSULTING"]
CAT_MAP = {c: i for i, c in enumerate(CATEGORIES)}
TERMS = [14, 30, 45, 60, 90]
START = date(2025, 1, 6)

rows = []
for i in range(1, N + 1):
    company = random.choice(COMPANY_CODES)
    category = random.choice(CATEGORIES)
    amount = min(round(random.lognormvariate(9.2, 1.0), 2), 950000.00)
    terms = random.choice(TERMS)
    risk = round(random.betavariate(2, 5), 3)
    prior_late = random.choices([0, 1, 2, 3, 5, 8],
                                weights=[40, 25, 15, 10, 6, 4])[0]
    dispute = 1 if random.random() < 0.08 else 0
    approvals = random.choices([1, 2, 3, 4], weights=[35, 35, 20, 10])[0]
    po_match = 1 if random.random() < 0.82 else 0

    doc_date = START + timedelta(days=random.randint(0, 420))
    net_due = doc_date + timedelta(days=terms)

    # Weighted signal. COMPANY_CODE absent on purpose.
    score = (
        -2.30
        + 2.60 * risk                                 # strongest driver
        + 0.22 * prior_late
        + 1.15 * dispute
        + 0.28 * (approvals - 1)
        + (0.85 if po_match == 0 else 0.0)
        + (0.45 if amount > 150000 else 0.0)
        + (0.30 if terms <= 14 else 0.0)
        + random.gauss(0, 0.55)
    )
    delayed = 1 if score > 0 else 0

    if delayed:
        delay_days = max(1, int(abs(random.gauss(14, 11))) + 1)
        clearing = net_due + timedelta(days=delay_days)
    else:
        delay_days = 0
        clearing = net_due - timedelta(days=random.randint(0, 9))

    rows.append((f"INV{i:07d}", f"V{random.randint(1, 180):05d}", company,
                 CAT_MAP[category], amount, terms, risk, prior_late,
                 dispute, approvals, po_match, net_due, clearing,
                 delay_days, delayed))

print("""-- Synthetic vendor payment data for the payment delay labs.
-- Generated by generate_payments.py (seed 42). Do not edit by hand.

CREATE SCHEMA ML_PAYMENT;

CREATE TABLE ML_PAYMENT.VENDOR_PAYMENTS (
  INVOICE_ID          NVARCHAR(12)  NOT NULL PRIMARY KEY,
  VENDOR_ID           NVARCHAR(10)  NOT NULL,
  COMPANY_CODE        NVARCHAR(4)   NOT NULL,
  CATEGORY_CODE       INTEGER       NOT NULL,
  INVOICE_AMOUNT      DECIMAL(15,2) NOT NULL,
  PAYMENT_TERMS_DAYS  INTEGER       NOT NULL,
  VENDOR_RISK_SCORE   DECIMAL(5,3)  NOT NULL,
  PRIOR_LATE_COUNT    INTEGER       NOT NULL,
  DISPUTE_FLAG        INTEGER       NOT NULL,
  APPROVAL_LEVELS     INTEGER       NOT NULL,
  PO_MATCH_FLAG       INTEGER       NOT NULL,
  NET_DUE_DATE        DATE          NOT NULL,
  CLEARING_DATE       DATE,
  DELAY_DAYS          INTEGER       NOT NULL,
  IS_DELAYED          INTEGER       NOT NULL
);
""")

for start in range(0, len(rows), 200):
    for r in rows[start:start + 200]:
        vals = (f"'{r[0]}','{r[1]}','{r[2]}',{r[3]},{r[4]},{r[5]},{r[6]},"
                f"{r[7]},{r[8]},{r[9]},{r[10]},'{r[11]}','{r[12]}',"
                f"{r[13]},{r[14]}")
        print(f"INSERT INTO ML_PAYMENT.VENDOR_PAYMENTS VALUES ({vals});")
    print("COMMIT;\n")

print("""
-- ============================================================
-- Verification. Check the signal before training anything.
-- ============================================================
SELECT COUNT(*) AS TOTAL_ROWS FROM ML_PAYMENT.VENDOR_PAYMENTS;

-- Expect roughly 25 percent delayed: imbalanced on purpose, so
-- scale_pos_weight and recall both matter.
SELECT IS_DELAYED, COUNT(*) AS CNT
FROM ML_PAYMENT.VENDOR_PAYMENTS
GROUP BY IS_DELAYED ORDER BY IS_DELAYED;

-- Expect a FLAT late rate across company codes. This column is noise
-- by design.
SELECT COMPANY_CODE, COUNT(*) AS INVOICES,
       ROUND(AVG(CASE WHEN IS_DELAYED = 1 THEN 1.0 ELSE 0.0 END) * 100, 1)
         AS LATE_PCT
FROM ML_PAYMENT.VENDOR_PAYMENTS
GROUP BY COMPANY_CODE ORDER BY COMPANY_CODE;

-- Expect late rate to CLIMB across risk bands (roughly 10, 20, 40).
-- If it does not, the data has no learnable signal and no model will
-- find one.
SELECT CASE WHEN VENDOR_RISK_SCORE < 0.2 THEN '1 low'
            WHEN VENDOR_RISK_SCORE < 0.4 THEN '2 medium'
            ELSE '3 high' END AS RISK_BAND,
       COUNT(*) AS INVOICES,
       ROUND(AVG(CASE WHEN IS_DELAYED = 1 THEN 1.0 ELSE 0.0 END) * 100, 1)
         AS LATE_PCT
FROM ML_PAYMENT.VENDOR_PAYMENTS
GROUP BY CASE WHEN VENDOR_RISK_SCORE < 0.2 THEN '1 low'
              WHEN VENDOR_RISK_SCORE < 0.4 THEN '2 medium'
              ELSE '3 high' END
ORDER BY RISK_BAND;
""")
